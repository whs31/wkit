use std::fmt::Write as _;

use crate::{Error, Result, WorkspaceManifest};

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct WorkspaceLock {
  pub revisions: std::collections::BTreeMap<String, String>,
}

impl WorkspaceLock {
  pub const FILE: &str = "workspace.lock";
  pub const HEADER: &str = "# Generated by `wkit ws lock`; edit workspace.toml, not this file.";

  pub fn load(path: &std::path::Path) -> Result<Self> {
    Self::parse(&WorkspaceManifest::read(path)?)
  }

  pub fn parse(text: &str) -> Result<Self> {
    let invalid = |message: String| Error::config(Self::FILE, message);
    let table: toml::Table =
      toml::from_str(text).map_err(|e| invalid(format!("invalid TOML: {e}")))?;
    if table.get("version").and_then(toml::Value::as_integer) != Some(WorkspaceManifest::VERSION) {
      return Err(invalid("`version` must be 1".to_owned()));
    }
    let entries = match table.get("revision") {
      None => &Vec::new(),
      Some(value) => value
        .as_array()
        .ok_or_else(|| invalid("expected `[[revision]]` entries".to_owned()))?,
    };
    let mut revisions = std::collections::BTreeMap::new();
    for entry in entries {
      let field = |key: &str| {
        entry
          .get(key)
          .and_then(toml::Value::as_str)
          .unwrap_or_default()
      };
      let path = field("path");
      if !crate::Member::is_valid_path(path) {
        return Err(invalid(format!(
          "project path must be normalized and relative: `{path}`"
        )));
      }
      if !Self::is_sha(field("commit")) {
        return Err(invalid(format!(
          "{path}: commit must be a lowercase 40-character SHA"
        )));
      }
      if revisions
        .insert(path.to_owned(), field("commit").to_owned())
        .is_some()
      {
        return Err(invalid(format!("duplicate locked project path: {path}")));
      }
    }
    Ok(Self { revisions })
  }

  pub fn check(&self, manifest: &WorkspaceManifest) -> Result<()> {
    let missing: Vec<_> = manifest
      .members
      .iter()
      .map(|m| m.path.as_str())
      .filter(|p| !self.revisions.contains_key(*p))
      .collect();
    if !missing.is_empty() {
      return Err(Error::config(
        Self::FILE,
        format!(
          "missing projects: {} (run `wkit ws lock`)",
          missing.join(", ")
        ),
      ));
    }
    let unknown: Vec<_> = self
      .revisions
      .keys()
      .filter(|p| manifest.member(p).is_none())
      .map(String::as_str)
      .collect();
    if !unknown.is_empty() {
      return Err(Error::config(
        Self::FILE,
        format!(
          "unknown projects: {} (run `wkit ws lock`)",
          unknown.join(", ")
        ),
      ));
    }
    Ok(())
  }

  pub fn commit(&self, path: &str) -> Option<&str> {
    self.revisions.get(path).map(String::as_str)
  }

  pub fn render(&self, manifest: &WorkspaceManifest) -> Result<String> {
    let mut text = format!("{}\nversion = 1\n", Self::HEADER);
    for member in &manifest.members {
      let commit = self
        .commit(&member.path)
        .filter(|c| Self::is_sha(c))
        .ok_or_else(|| {
          Error::config(
            Self::FILE,
            format!("{}: no valid commit to write", member.path),
          )
        })?;
      let _ = write!(
        text,
        "\n[[revision]]\npath = \"{}\"\ncommit = \"{commit}\"\n",
        member.path
      );
    }
    Ok(text)
  }

  pub fn is_sha(text: &str) -> bool {
    text.len() == 40 && text.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
  }
}

#[cfg(test)]
mod tests {
  use super::*;

  const A: &str = "f047e85e4896be52e55d70750a0a530087301b42";
  const B: &str = "fd828533ee7a4f22ccd8eceac3625aaf7dcd253c";

  fn manifest() -> WorkspaceManifest {
    WorkspaceManifest::parse(
      "version = 1\n[[project]]\npath='b/one'\nurl='u'\nbranch='m'\n[[project]]\npath='a/two'\nurl='v'\nbranch='m'\n",
    )
    .unwrap()
  }

  #[test]
  fn renders_in_manifest_order_and_reads_back() {
    let mut lock = WorkspaceLock::default();
    lock.revisions.insert("b/one".into(), A.into());
    lock.revisions.insert("a/two".into(), B.into());
    let text = lock.render(&manifest()).unwrap();
    assert_eq!(
      text,
      format!(
        "{}\nversion = 1\n\n[[revision]]\npath = \"b/one\"\ncommit = \"{A}\"\n\n[[revision]]\npath = \"a/two\"\ncommit = \"{B}\"\n",
        WorkspaceLock::HEADER
      )
    );
    let read = WorkspaceLock::parse(&text).unwrap();
    assert_eq!(read, lock);
    read.check(&manifest()).unwrap();
  }

  #[test]
  fn locks_must_cover_the_manifest_exactly() {
    let one = WorkspaceLock::parse(&format!(
      "version = 1\n[[revision]]\npath = \"b/one\"\ncommit = \"{A}\"\n"
    ))
    .unwrap();
    assert!(
      one
        .check(&manifest())
        .unwrap_err()
        .to_string()
        .contains("missing projects: a/two")
    );
    let extra = format!(
      "version = 1\n[[revision]]\npath = \"b/one\"\ncommit = \"{A}\"\n[[revision]]\npath = \"a/two\"\ncommit = \"{A}\"\n[[revision]]\npath = \"c\"\ncommit = \"{A}\"\n"
    );
    let err = WorkspaceLock::parse(&extra)
      .unwrap()
      .check(&manifest())
      .unwrap_err();
    assert!(err.to_string().contains("unknown projects: c"), "{err}");
    let bad = WorkspaceLock::parse("version = 1\n[[revision]]\npath = \"x\"\ncommit = \"ABC\"\n")
      .unwrap_err();
    assert!(bad.to_string().contains("40-character SHA"));
  }
}
